"""Identity and session lifecycle: the whole of requirement R1's business logic.

Registration, credential verification, token-pair issuance, refresh rotation with reuse
detection, and revocation on logout. This is the first authentication code this repository has
ever contained - the source branch has no role, no permission, no owner and no principal
anywhere - so every rule below is stated here rather than inherited from somewhere older.

Authority is decided here, on the server
----------------------------------------
Nothing a caller sends decides what they may become. :class:`~app.schemas.auth.RegisterRequest`
has no ``role`` field and forbids unknown keys, so ``{"role": "ADMIN"}`` in a registration body
is a ``422`` rather than a privilege quietly granted; the role a new account receives is chosen
by :meth:`AuthService.register` and by the ``'READER'::user_role`` server default behind it.
``ADMIN`` is reachable only by seeding (``app.db.seed``) or by an existing administrator through
``admin_service`` - never by self-registration, and never by anything in this file.

The client also supplies no identifier and no timestamp. ``id`` comes from PostgreSQL's
``gen_random_uuid()``, the audit instants come from the database clock, and the two ``CITEXT``
UNIQUE indexes on ``users.email`` and ``users.username`` - not the pre-check in
:meth:`AuthService.register` - are what actually make a duplicate account unstorable.

Two failures that must stay indistinguishable
---------------------------------------------
An authentication API leaks its user list through the *difference* between its refusals, so two
pairs of paths are deliberately collapsed here:

* **Login.** An unknown email and a wrong password raise the same class with the same
  :data:`_INVALID_CREDENTIALS` message, and both pay the same argon2 verification cost - the
  unknown-email path verifies against :func:`~app.core.security.dummy_password_hash_async`
  precisely
  so the timing cannot be read as "is this address registered?".
* **Registration.** A taken email and a taken username raise the same
  :class:`~app.core.exceptions.ConflictError` with the same :data:`_IDENTIFIER_TAKEN` message,
  so a caller learns that *something* collided and never *which* - otherwise the registration
  route becomes an oracle for both the address list and the handle list.

Deactivation is the one refusal that is deliberately *not* collapsed into those, because it is a
different question: the credential was genuine. It answers ``403`` with the same message
``get_current_active_user`` uses, so a client sees one consistent story about a suspended
account whether it is signing in or presenting a token it already holds.

Only hashes are persisted, and only once
----------------------------------------
Two secrets pass through this module and neither is stored as given. A password is argon2id
hashed by :func:`~app.core.security.hash_password_async` and the plaintext is dropped when the call
returns. A refresh token is generated by :func:`~app.core.security.generate_refresh_token`,
returned to the caller exactly once inside a :class:`~app.schemas.auth.TokenPair`, and reaches
the database only as the SHA-256 digest from :func:`~app.core.security.hash_refresh_token`. A
database disclosure therefore yields no usable session and no usable password, and neither
value is ever a log field: the only line this module emits carries a user identifier and a
count.

Rotation is one atomic claim, and reuse is a security event
-----------------------------------------------------------
:meth:`AuthService.rotate_refresh_token` spends the presented token through
:meth:`~app.repositories.user_repository.RefreshTokenRepository.claim`, which tests and revokes
the row in a single ``UPDATE ... RETURNING`` under one row lock. That is what makes a refresh
token single-use in the presence of concurrency: reading the row and revoking it afterwards
would let two requests presenting one digest both conclude it was good and both mint a
replacement.

A claim that comes back empty is then *diagnosed* through
:meth:`~app.repositories.user_repository.RefreshTokenRepository.get_by_hash`, which filters
nothing and so can see a row that is already spent. A digest presented twice is the observable
signature of a leaked token, so it is answered by revoking every token the account still holds -
the whole family, not merely the row presented - and by emitting the one log line this module
writes. Everything else about a failed exchange is answered identically, because telling a
caller which check failed is telling an attacker which one to fix.

What this module is, and is not
-------------------------------
* **Business rules only.** No SQL, no statement, no session construction: every query lives in
  ``app.repositories``, reached through the barrel, and this file never imports
  ``app.db.session``.
* **No HTTP concern.** No ``fastapi`` import, no ``HTTPException``, no status-code literal, no
  response envelope. Failures leave as the domain classes in ``app.core.exceptions`` and
  ``app.api.v1.routers.auth`` renders them - the previous service raised
  ``HTTPException(404, "Item not found")`` from inside three separate data-access loops
  (``app.py:L31``, ``L40``, ``L49``) and wrapped results in a ``message``/``data`` envelope
  (``app.py:L18``, ``L39``); neither pattern reappears here.
* **No cryptography.** ``PyJWT`` and ``pwdlib`` are reached only through ``app.core.security``,
  which owns them, so hashing parameters and token claims have exactly one definition site.
* **No configuration reading.** Lifetimes come from ``settings``; there is no environment
  access and no hard-coded secret or duration anywhere below.
* **Schema-shaped results.** Token operations return :class:`~app.schemas.auth.TokenPair` and
  identity operations return the mapped :class:`~app.models.user.User`, which the router
  projects into ``UserPublic`` or ``UserMe``. Never an ad-hoc dictionary.
* **No module-level mutable state.** Only the immutable constants below, and a repository is
  bound to a session per instance rather than shared - the opposite of the ``items = []``
  process-global the previous service used as its entire datastore (``app.py:L6-L7``).

The transaction boundary belongs to this layer
----------------------------------------------
``app.repositories`` flushes and never commits, so each mutating method here commits its own
unit of work and lets every exception propagate: ``get_db`` rolls the session back on the way
out, and the suite's fixture rolls each test back afterwards. Rotation commits **once**, inside
:meth:`AuthService.issue_token_pair`, so the claim that spends the old token and the row that
records its replacement become durable together - a token can never be spent without a
replacement existing.

``session.begin()`` is never called. The session arrives already inside a transaction in both
callers - ``get_db`` in the API tier and the transactional fixture in the suite - and opening a
second one would collide with the outer transaction the suite rolls back.
"""

