# ---------------------------------------------------------------------------------------
# Refusal messages
#
# Constants rather than inline literals, because the *sameness* of two messages is a security
# property here rather than a matter of tidiness. Two call sites raising "the same" refusal by
# each spelling it out is how the two quietly diverge - a comma added to one of them turns the
# login route back into an account-enumeration oracle, and no test that asserts on either
# message alone would notice. Naming each message once makes the two paths byte-identical by
# construction, which is what `backend/tests/integration/test_auth_api.py` asserts.
#
# Every string below is written to be safe in front of an unauthenticated caller: none names a
# column, an identifier, a configuration value or the existence of any account.
# ---------------------------------------------------------------------------------------

_IDENTIFIER_TAKEN: Final[str] = "That email address or username is already registered."

_REGISTRATION_UNIQUE_CONSTRAINTS: Final[frozenset[str]] = frozenset(
    {"ix_users_email", "ix_users_username"}
)
"""The only two constraints a concurrent registration can legitimately violate.

Both are unique ``citext`` indexes created under these names by revision ``0001``, and both mean
exactly what :data:`_IDENTIFIER_TAKEN` says. Every other constraint on ``users`` describes an
invariant this service is supposed to satisfy on its own - a ``NOT NULL`` column it failed to
populate, a check it failed to respect - so a violation of one is a defect here, not a race, and is
re-raised untouched so it surfaces as a ``500`` with frames.
"""

_REGISTRATION_SQLSTATES: Final[frozenset[str]] = frozenset({"23505"})
"""``unique_violation`` - the only class a concurrent registration can produce.

``23503`` is absent because a new account references nothing. ``23502`` and ``23514`` are absent
because a ``NOT NULL`` or check violation means the row assembled above was wrong.
"""

"""Registration conflict, for a taken email **and** for a taken username alike.

Deliberately ambiguous. Reporting which of the two collided would answer "is this address
registered?" and "is this handle taken?" as separate questions, which together enumerate both
columns; the caller learns only that one of the two identifiers needs changing. Raised from the
pre-check and from the ``CITEXT`` unique violation that backs it, so the two are
indistinguishable from outside as well.
"""

_INVALID_CREDENTIALS: Final[str] = "Incorrect email or password."
"""Login failure, for an unknown email **and** for a wrong password alike.

The wording names both fields on purpose: it is accurate in either case, and it is the sentence
a client can render verbatim. See :meth:`AuthService.authenticate` for the matching guarantee
that the two paths also cost the same.
"""

_ACCOUNT_DEACTIVATED: Final[str] = "This account has been deactivated."
"""A genuine credential belonging to a suspended account.

Character-for-character the message ``app.core.dependencies.get_current_active_user`` raises, so
the same account gets the same explanation whether it is signing in or presenting a token it
already holds. Disclosing this is not enumeration: the caller has already proved they hold the
password for the account, so they learn nothing they did not supply.
"""

_INVALID_REFRESH_TOKEN: Final[str] = "The refresh token is invalid or has expired."
"""Every failed exchange at the refresh route, whatever the cause.

One message for a digest that was never issued, one already spent, one past its expiry and one
whose account has since been removed or deactivated. The causes are distinguished internally -
a spent digest triggers family revocation and the module's one log line - but never in the
response, because naming the failed check tells an attacker which one to fix next.
"""


