"""Three views of an account: what anyone may see, what its owner may see, what it may change.

``users`` is the only relation in this schema read by three different audiences, and this module
is where those audiences are held apart. Three models, three surfaces, no overlap:

* :class:`UserPublic` goes out to anyone. It is the response of ``POST /api/v1/auth/register``
  and of ``GET /api/v1/users/{username}``, and it is the ``author`` member embedded in every
  post, every comment and every administrative row.
* :class:`UserMe` goes out to the authenticated principal, and describes that principal's own
  record only. It is the response of ``GET /api/v1/auth/me`` and of ``PATCH /api/v1/users/me``.
* :class:`UserUpdate` comes in from the authenticated principal, and carries the three profile
  members that principal is permitted to change.

The confidentiality boundary of the whole API lives in this file
---------------------------------------------------------------
:class:`UserPublic` is not one response among many. It is the only user projection permitted to
nest inside another resource, so ``app.schemas.post`` embeds it as a post's author,
``app.schemas.comment`` as a comment's author, and ``app.schemas.admin`` as the subject of an
administrative row. Every one of those surfaces inherits its field list verbatim, which means a
member added here does not leak on one endpoint - it leaks on all of them at once: in the feed a
crawler reads, in the comment thread under every post, and on every profile the sitemap links to.

Four members are therefore withheld, and the omissions are the contract rather than an oversight:

``password_hash``
    Absent from every model in this module and from every model in ``app.schemas``. No schema
    anywhere in this service carries it. ``app.core.security`` produces the argon2id hash and
    verifies a candidate against it; nothing publishes it, logs it or echoes it back.
``email``
    An address no reader has a reason to see. It appears on :class:`UserMe`, where the caller
    *is* the address's owner, and in the administrative user projection. Nowhere else.
``role``
    Authority is not public. Publishing it beside a byline would advertise which accounts are
    administrators - reconnaissance handed out for free, on every post card.
``is_active``
    Whether an account has been suspended is a moderation fact about a person, not profile
    content, and disclosing it would leak an administrative decision to anonymous readers.

Deriving the second model from the first, rather than restating it
-----------------------------------------------------------------
:class:`UserMe` inherits :class:`UserPublic` and adds four members. The two therefore cannot
drift: a description corrected on one is corrected on both, and a field the public projection
stops publishing disappears from the self view in the same edit rather than surviving there
unnoticed.

Inheritance is emphatically **not** permission to embed. :class:`UserMe` is returned by exactly
two routes, both of which have already resolved the caller and are describing that caller's own
record. It must never appear as a nested member of another resource, because nesting is how the
three withheld members it does carry - ``email``, ``role`` and ``is_active``; never
``password_hash``, which it withholds too - would reach an audience that does not own them. A
reviewer checking this property has a one-line test: ``author: UserPublic`` is correct in a
sibling module, and ``author: UserMe`` is a defect.

Exposing the caller's ``email``, ``role`` and ``is_active`` *to the caller* is not a leak. The
caller owns that data, and the account settings screen cannot be written without it. The
prohibition is on the public projection, which is why ``POST /api/v1/auth/register`` answers with
:class:`UserPublic` even though the request came from the account's own owner - a registration
reply has no need of the members :class:`UserMe` adds, so it does not carry them.

What replaced ``Item``
---------------------
The service this repository grew out of had exactly one data contract, and it faced both ways at
once: the same three-field model was the accepted request body and the returned representation.
Two properties of that arrangement are defects this module closes.

The client supplied identity. ``id`` arrived in the request body, the server never generated it
and never checked it for uniqueness. Here ``id`` appears on the two *output* models and on
neither input: it is generated by PostgreSQL, and :class:`UserUpdate` has no member through which
a caller could propose one.

A write accepted whatever a read returned. Because one model served both directions, every field
a response published was a field a request could set - so a projection and a privilege boundary
were the same declaration. Splitting them is what makes ``role`` publishable to its owner and
unsettable by them.

What this module does not do
----------------------------
It declares shapes. There is no session, no statement, no ownership rule, no status code and no
error construction anywhere below. ``app.services.profile_service`` assembles a profile and
applies an update, ``app.repositories.user_repository`` owns every statement,
``app.core.dependencies`` resolves the principal from the bearer token, and
``app.core.exceptions`` renders a failure as the single problem document. This module reads no
configuration: no environment variable, no dotenv file, no import of ``app.core.config``.

It runs no uniqueness check either. ``users.email`` and ``users.username`` are ``CITEXT UNIQUE``,
so the database answers "is this taken?" authoritatively for simultaneous and case-variant
submissions alike, and ``app.services.auth_service`` translates the violation into a ``409``.
Nothing here lower-cases an identifier: an application-side fold would have to be applied on
every write path and every lookup path, and the first path that forgot would admit the duplicate
the ``CITEXT`` index forbids.

There is no collection wrapper here. ``GET /api/v1/users/{username}/posts`` returns
``Page[PostSummary]``, and ``Page`` is declared once, in ``app.core.pagination``, and re-exported
by ``app.schemas.common``.

The two directions disagree about one type, deliberately
-------------------------------------------------------
``avatar_url`` is :class:`~pydantic.HttpUrl` on the way in and ``str`` on the way out. Inbound,
the value is caller-supplied and has to be proved to be an absolute ``http`` or ``https`` URL
before it reaches a column that will be interpolated into an ``<img src>``. Outbound, the value
was already validated when it was stored, so re-parsing it on every byline would cost a parse per
row and would turn a legacy row that no longer parses into a ``500`` on a read path.

The consequence for the service layer is stated on the field itself and repeated here because it
is the one cross-layer obligation this module imposes: :class:`~pydantic.HttpUrl` validates to a
``Url`` object, not to a :class:`str`, so an update must be coerced with ``str(value)`` before it
is assigned to the ``Text`` column.

Import purity
-------------
Four imports: the standard library's :mod:`uuid` and :class:`~datetime.datetime`, the typing
constructs the annotated aliases need, ``pydantic``, and :class:`~app.models.user.UserRole` from
``app.models``.

That last one is a single edge and it points the right way. ``app.models`` does not import
``app.schemas``, so there is no cycle, and taking the enumeration from the module that persists
it means the wire labels and the PostgreSQL ``user_role`` labels are one declaration rather than
two that can disagree the first time a role is added on one side only.

No sibling schema module is imported, and none may be. ``app.schemas.auth`` also bounds a display
name, and the bound below is restated rather than imported from it: an import between siblings
would make this package's import order load-bearing, for a number that has to agree with the
registration contract in any case - see :data:`DISPLAY_NAME_MAX_LENGTH`.
"""

